import { emptyBookmarkValues, validateBookmark } from "@signet/core/bookmarks";
import { Typography } from "@signet/design-system";
import {
  colors,
  radii,
  spacing,
  typography,
} from "@signet/design-system/tokens.css";
import { useCallback, useEffect, useState } from "react";
import { css, html } from "react-strict-dom";
import { browser } from "wxt/browser";
import { popupColors } from "./popup-tokens.css";

const applicationId = "co.signetapp.app";
const darkMode = "@media (prefers-color-scheme: dark)";
const smallViewport = "@media (max-width: 480px)";

/** Requests accepted by the containing Signet app. */
type NativeMessage =
  | { action: "getSession" }
  | { action: "saveBookmark"; title: string; url: string };

/** Statuses returned by the Safari native extension handler. */
type NativeStatus =
  | "ready"
  | "saved"
  | "duplicate"
  | "signedOut"
  | "unauthorized"
  | "offline"
  | "invalid"
  | "failed";

/** Native messaging response payload. */
type NativeResponse = {
  status?: NativeStatus;
};

/** Typed WebExtension message names generated by WXT. */
type MessageKey = Parameters<typeof browser.i18n.getMessage>[0];

/** Visual state and localized content for the popup status. */
type PopupStatus = {
  state: "error" | "success" | "duplicate" | "info" | null;
  titleKey: MessageKey | "";
  messageKey: MessageKey;
};

const translate = (key: MessageKey): string => browser.i18n.getMessage(key);

const sendNativeMessage = (
  message: NativeMessage,
): Promise<NativeResponse | null> =>
  browser.runtime.sendNativeMessage(applicationId, {
    ...message,
    language: browser.i18n.getUILanguage(),
  }) as Promise<NativeResponse | null>;

export const Popup = () => {
  const [bookmarkUrl, setBookmarkUrl] = useState<string | null>(null);
  const [canSave, setCanSave] = useState(false);
  const [form, setForm] = useState<HTMLFormElement | null>(null);
  const [saving, setSaving] = useState(false);
  const [signedOut, setSignedOut] = useState(false);
  const [status, setStatus] = useState<PopupStatus | null>({
    state: null,
    titleKey: "",
    messageKey: "loading",
  });
  const [title, setTitle] = useState("");
  const [titleError, setTitleError] = useState(false);
  const [titleInput, setTitleInput] = useState<HTMLInputElement | null>(null);

  const handleOpenApp = useCallback((): void => {
    window.location.href = "signet://";
  }, []);

  const handleSubmit = useCallback(
    async (event: Event): Promise<void> => {
      event.preventDefault();
      if (!canSave || saving || !bookmarkUrl) return;

      const trimmedTitle = title.trim();
      const validation = validateBookmark({
        ...emptyBookmarkValues,
        title: trimmedTitle,
        url: bookmarkUrl,
      });
      if (validation.title) {
        setTitleError(true);
        titleInput?.focus();
        return;
      }
      if (validation.url) {
        setCanSave(false);
        setStatus({
          state: "error",
          titleKey: "",
          messageKey: "unsupported_page",
        });
        return;
      }

      setSaving(true);
      setStatus(null);

      try {
        const response = await sendNativeMessage({
          action: "saveBookmark",
          title: trimmedTitle,
          url: bookmarkUrl,
        });

        switch (response?.status) {
          case "saved":
            setCanSave(false);
            setStatus({
              state: "success",
              titleKey: "saved_title",
              messageKey: "saved_message",
            });
            break;
          case "duplicate":
            setCanSave(false);
            setStatus({
              state: "duplicate",
              titleKey: "already_saved_title",
              messageKey: "already_saved_message",
            });
            break;
          case "signedOut":
            setCanSave(false);
            setSignedOut(true);
            setStatus({
              state: "info",
              titleKey: "signed_out_title",
              messageKey: "signed_out_message",
            });
            break;
          case "unauthorized":
            setCanSave(false);
            setSignedOut(true);
            setStatus({
              state: "error",
              titleKey: "session_expired_title",
              messageKey: "session_expired_message",
            });
            break;
          case "offline":
            setStatus({
              state: "error",
              titleKey: "",
              messageKey: "offline_message",
            });
            break;
          default:
            setStatus({
              state: "error",
              titleKey: "",
              messageKey: "save_failed",
            });
        }
      } catch {
        setStatus({
          state: "error",
          titleKey: "",
          messageKey: "save_failed",
        });
      } finally {
        setSaving(false);
      }
    },
    [bookmarkUrl, canSave, saving, title, titleInput],
  );

  useEffect(() => {
    let active = true;
    document.documentElement.lang = browser.i18n.getUILanguage();
    document.title = translate("popup_title");

    const initialize = async (): Promise<void> => {
      try {
        const [tabs, session] = await Promise.all([
          browser.tabs.query({ active: true, currentWindow: true }),
          sendNativeMessage({ action: "getSession" }),
        ]);
        if (!active) return;

        const tab = tabs[0];
        const nextBookmarkUrl = tab?.url ?? null;

        const validation = validateBookmark({
          ...emptyBookmarkValues,
          title: tab?.title || nextBookmarkUrl || "",
          url: nextBookmarkUrl || "",
        });
        if (!nextBookmarkUrl || validation.url) {
          setStatus({
            state: "error",
            titleKey: "",
            messageKey: "unsupported_page",
          });
          return;
        }

        setBookmarkUrl(nextBookmarkUrl);
        setTitle(tab?.title || nextBookmarkUrl);
        if (session?.status !== "ready") {
          setSignedOut(true);
          setStatus({
            state: "info",
            titleKey: "signed_out_title",
            messageKey: "signed_out_message",
          });
          return;
        }

        setCanSave(true);
        setStatus(null);
      } catch {
        if (active) {
          setStatus({
            state: "error",
            titleKey: "",
            messageKey: "load_failed",
          });
        }
      }
    };

    void initialize();
    return () => {
      active = false;
    };
  }, []);

  useEffect(() => {
    if (!form) return;
    form.noValidate = true;
    const submitListener = (event: Event): void => {
      void handleSubmit(event);
    };
    form.addEventListener("submit", submitListener);
    return () => form.removeEventListener("submit", submitListener);
  }, [form, handleSubmit]);

  const controlsDisabled = !canSave || saving;
  const statusState = status?.state ?? "default";

  return (
    <html.main data-layoutconformance="strict" style={styles.main}>
      <html.header style={styles.header}>
        <html.img
          alt=""
          height={32}
          src="/images/signet-logo-light.png"
          style={styles.logoLight}
          width={32}
        />
        <html.img
          alt=""
          height={32}
          src="/images/signet-logo-dark.png"
          style={styles.logoDark}
          width={32}
        />
        <html.div>
          <Typography
            as="h1"
            style={styles.title}
            tone="accent"
            variant="title"
          >
            {translate("popup_title")}
          </Typography>
          <Typography
            as="p"
            style={styles.subtitle}
            tone="secondary"
            variant="caption"
          >
            {translate("popup_subtitle")}
          </Typography>
        </html.div>
      </html.header>

      <html.form id="bookmark-form" ref={setForm} style={styles.form}>
        <html.div hidden={signedOut ? true : undefined} style={styles.field}>
          <Typography
            as="label"
            for="bookmark-title"
            style={styles.label}
            tone="accent"
            variant="caption"
          >
            {translate("title_label")}
          </Typography>
          <html.input
            aria-describedby="title-error"
            aria-invalid={titleError ? true : undefined}
            autoComplete="off"
            disabled={controlsDisabled}
            id="bookmark-title"
            name="title"
            onChange={(event: unknown) => {
              const change = event as { target?: { value?: string } };
              setTitle(change.target?.value ?? "");
              setTitleError(false);
            }}
            ref={setTitleInput}
            required
            style={[
              styles.input,
              titleError && styles.inputError,
              controlsDisabled && styles.inputDisabled,
            ]}
            type="text"
            value={title}
          />
          <Typography
            as="p"
            hidden={titleError ? undefined : true}
            id="title-error"
            style={styles.fieldError}
            tone="danger"
            variant="caption"
          >
            {titleError ? translate("title_required") : ""}
          </Typography>
        </html.div>

        <html.fieldset
          aria-labelledby="url-label"
          hidden={signedOut ? true : undefined}
          style={[styles.field, styles.fieldset]}
        >
          <Typography
            id="url-label"
            style={styles.label}
            tone="accent"
            variant="caption"
          >
            {translate("url_label")}
          </Typography>
          <Typography
            as="p"
            id="bookmark-url"
            style={styles.url}
            tone="secondary"
            variant="caption"
          >
            {bookmarkUrl ?? ""}
          </Typography>
        </html.fieldset>

        <html.div
          aria-live="polite"
          hidden={status ? undefined : true}
          id="status"
          role="status"
          style={[styles.status, statusSurfaceStyles[statusState]]}
        >
          <Typography
            as="strong"
            hidden={status?.titleKey ? undefined : true}
            id="status-title"
            style={[
              styles.statusTitle,
              statusTextStyles[statusState],
              status?.state === "duplicate" && styles.duplicateTitle,
            ]}
          >
            {status?.titleKey ? translate(status.titleKey) : ""}
          </Typography>
          <Typography
            as="p"
            id="status-message"
            style={[
              styles.statusMessage,
              statusTextStyles[statusState],
              Boolean(status?.titleKey) && styles.statusMessageWithTitle,
            ]}
            variant="caption"
          >
            {status ? translate(status.messageKey) : ""}
          </Typography>
        </html.div>

        <html.button
          disabled={controlsDisabled}
          hidden={signedOut ? true : undefined}
          id="save-button"
          style={[styles.button, controlsDisabled && styles.buttonDisabled]}
          type="submit"
        >
          <Typography style={styles.buttonLabel}>
            {translate(saving ? "saving" : "save")}
          </Typography>
        </html.button>
        <html.button
          hidden={signedOut ? undefined : true}
          id="open-app-button"
          onClick={handleOpenApp}
          style={styles.button}
          type="button"
        >
          <Typography style={styles.buttonLabel}>
            {translate("open_app")}
          </Typography>
        </html.button>
      </html.form>
    </html.main>
  );
};

